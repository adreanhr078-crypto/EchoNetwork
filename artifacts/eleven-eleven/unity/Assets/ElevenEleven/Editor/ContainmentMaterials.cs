using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;
using UnityEngine.Rendering;

namespace ElevenEleven.Editor
{
    internal static class ContainmentMaterials
    {
        private const string Folder = "Assets/ElevenEleven/Opening/Stormworks/";

        internal static void Specimens(Transform art, Material deck)
        {
            GodotRoomAssembly.Find(art, "Floor").GetComponentInChildren<MeshRenderer>(true).sharedMaterial = deck;
            var glass = Optics("Specimen laminated glass", new Color(0.13f, 0.59f, 0.79f, 0.35f), 0, 3002);
            var coolant = Optics("Specimen circulating serum", new Color(0.045f, 0.45f, 0.56f, 0.43f), 1, 3001);
            var anomaly = Optics("EX-011 amber serum", new Color(1f, 0.43f, 0.082f, 0.54f), 1, 3001);
            foreach (var id in new[] { "005", "007", "008", "009", "010", "011" })
            {
                var tank = GodotRoomAssembly.Find(art, "Tank_ex_" + id);
                var layers = tank.GetComponentsInChildren<MeshRenderer>(true).Where(r => r.transform.parent == tank)
                    .OrderByDescending(r => r.localBounds.size.y).ToArray();
                if (layers.Length != 2) throw new InvalidDataException($"Expected two visible liquid boundaries for EX-{id}");
                Apply(layers[0], glass);
                Apply(layers[1], id == "011" ? anomaly : coolant);
            }

            // Godot's projected scanner field is regenerated by the live Unity light.
            var scanner = GodotRoomAssembly.Find(art, "ScannerHead");
            foreach (var mesh in scanner.GetComponentsInChildren<MeshRenderer>(true))
                if (mesh.transform.parent == scanner && mesh.localBounds.size.magnitude > 3)
                    mesh.enabled = false;
        }

        internal static void Archive(Transform art, Material deck)
        {
            GodotRoomAssembly.Find(art, "Floor").GetComponentInChildren<MeshRenderer>(true).sharedMaterial = deck;
            var core = GodotRoomAssembly.Find(art, "CoreBeamPillar").GetComponent<MeshRenderer>();
            Apply(core, Optics("Archive memory projection", new Color(0.55f, 0.25f, 1.6f, 0.77f), 2, 3003));
        }

        private static void Apply(MeshRenderer renderer, Material material)
        {
            renderer.sharedMaterial = material;
            renderer.shadowCastingMode = ShadowCastingMode.Off;
            renderer.receiveShadows = false;
        }

        private static Material Optics(string name, Color tint, float mode, int queue)
        {
            var path = Folder + name + ".mat";
            var asset = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (asset == null)
            {
                var shader = AssetDatabase.LoadAssetAtPath<Shader>(Folder + "ContainmentOptics.shader")
                    ?? throw new InvalidDataException("Containment material shader missing.");
                asset = new Material(shader);
                AssetDatabase.CreateAsset(asset, path);
            }
            asset.SetColor("_Tint", tint);
            asset.SetFloat("_Mode", mode);
            asset.renderQueue = queue;
            EditorUtility.SetDirty(asset);
            AssetDatabase.SaveAssetIfDirty(asset);
            return asset;
        }
    }
}

